import assert from 'node:assert/strict';
import {deriveMarketOrigin,marketWorldCoordinates,applyMarketOriginOnce} from '../runtime/market-origin-runtime.mjs';
const state={axes:{KX:{market:'BTCUSDT'},KY:{market:'BNBUSDT'},KZ:{market:'KGENUSDT'}},quotes:{BTCUSDT:61234.5,BNBUSDT:842.1,KGENUSDT:-0.25},xyz:{x:0,y:0,z:0},intentXYZ:{x:0,y:0,z:0}};
const d=deriveMarketOrigin(state);
assert.equal(d.ready,true);
assert.deepEqual(d.origin,{x:61234.5,y:842.1,z:-0.25});
assert.deepEqual(marketWorldCoordinates(d.origin,{x:-100,y:2,z:5}),{x:61134.5,y:844.1,z:4.75});
const a=applyMarketOriginOnce(state);
assert.equal(a.applied,true);
assert.deepEqual(state.xyz,{x:0,y:0,z:0},'local physical/render frame must stay at the local origin');
assert.deepEqual(state.marketWorldXYZ,{x:61234.5,y:842.1,z:-0.25});
state.intentXYZ.x=-100;
assert.deepEqual(marketWorldCoordinates(state.marketOrigin,state.intentXYZ),{x:61134.5,y:842.1,z:-0.25},'signed player movement offsets the market origin');
assert.equal(applyMarketOriginOnce(state).applied,false,'market origin must not reset during play');
console.log('11520 market-origin runtime PASS');
