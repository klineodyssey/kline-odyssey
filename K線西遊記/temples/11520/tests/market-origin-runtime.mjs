import assert from 'node:assert/strict';
import {deriveMarketOrigin,applyMarketOriginOnce} from '../runtime/market-origin-runtime.mjs';
const state={axes:{KX:{market:'BTCUSDT'},KY:{market:'BNBUSDT'},KZ:{market:'KGENUSDT'}},quotes:{BTCUSDT:61234.5,BNBUSDT:842.1,KGENUSDT:-0.25}};
const d=deriveMarketOrigin(state);
assert.equal(d.ready,true);
assert.deepEqual(d.origin,{x:61234.5,y:842.1,z:-0.25});
const a=applyMarketOriginOnce(state);
assert.equal(a.applied,true);
assert.deepEqual(state.xyz,{x:61234.5,y:842.1,z:-0.25});
state.xyz.x-=100;
assert.equal(state.xyz.x,61134.5,'autonomous signed movement remains relative to market-derived origin');
assert.equal(applyMarketOriginOnce(state).applied,false,'origin must not reset during play');
console.log('11520 market-origin runtime PASS');
